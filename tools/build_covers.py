SC=0.5
def segs(im):
    a=np.array(im)[...,3];lab,n=ndi.label(ndi.binary_dilation(a>60,iterations=1));out=[]
    for sl in ndi.find_objects(lab):
        y0,y1,x0,x1=sl[0].start,sl[0].stop,sl[1].start,sl[1].stop
        if x1-x0>=70 and y1-y0>=60:out.append((x0,y0,x1,y1))
    return out,a
